# Precompiled once at import time (hot path).
_COMPILED = [(re.compile(p), r) for p, r in _RULES]


class Rabbit:
    @staticmethod
    def zg2uni(text):
        for pattern, repl in _COMPILED:
            text = pattern.sub(repl, text)
        return text
